upcoming_matches['predicted_lambda_away'] = [1.1, 1.2, 1.6, 1.1]

# ==========================================
# 4. SIMULACIÓN MONTE CARLO (POISSON 1X2)
# ==========================================
def run_monte_carlo(l_home, l_away, n_simulations=10000):
    home_goals = np.random.poisson(l_home, n_simulations)
    away_goals = np.random.poisson(l_away, n_simulations)

    prob_1 = np.sum(home_goals > away_goals) / n_simulations * 100
    prob_X = np.sum(home_goals == away_goals) / n_simulations * 100
    prob_2 = np.sum(away_goals > home_goals) / n_simulations * 100

    return round(prob_1, 1), round(prob_X, 1), round(prob_2, 1)

probs_1, probs_X, probs_2 = [], [], []

for _, row in upcoming_matches.iterrows():
    p1, px, p2 = run_monte_carlo(row['predicted_lambda_home'], row['predicted_lambda_away'])
    probs_1.append(p1)
    probs_X.append(px)
    probs_2.append(p2)

upcoming_matches['Prob_1 (%)'] = probs_1
upcoming_matches['Prob_X (%)'] = probs_X
upcoming_matches['Prob_2 (%)'] = probs_2

